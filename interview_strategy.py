def get_company_strategy(company_name: str) -> dict:
    company_lower = company_name.lower()

    for company_key, strategy in COMPANY_STRATEGIES.items():
        if company_key in company_lower:
            return strategy

    return DEFAULT_STRATEGY


def build_interview_strategy(opportunity_data: dict, score: int) -> str:
    if score < 80:
        return ""

    company = opportunity_data.get("company", "")
    strategy = get_company_strategy(company)

    return f"""
خطة الوصول للمقابلة:
- قدّم من الرابط.
- ابحث في LinkedIn عن: {strategy["people"]}.
- المشروع الأنسب: {strategy["project"]}.
- سبب الربط: {strategy["why"]}

رسالة جاهزة:
{strategy["message"]}"""
