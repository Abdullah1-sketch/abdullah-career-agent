def build_manual_visit_radar(limit: int = 3) -> str:
    targets = [
        target for target in MANUAL_VISIT_TARGETS
        if target["city"] in ["الرياض", "القصيم"]
    ]

    targets = sorted(
        targets,
        key=lambda item: item["visit_score"],
        reverse=True,
    )[:limit]

    lines = ["رادار التقديم اليدوي - الرياض والقصيم فقط:"]

    for index, target in enumerate(targets, start=1):
        manual_action = (
            "نعم، قدّم يدويًا إذا كنت قريبًا أو عندك يوم مخصص للتقديم."
            if target["manual_visit_recommended"]
            else "لا تجعله زيارة أساسية إلا إذا ظهر شاغر قوي أو عرفت أن المقر يستقبل طلبات."
        )

        lines.append(
            f"""
{index}. {target["company"]} ({target["arabic_label"]})
المدينة: {target["city"]}
درجة أولوية الزيارة: {target["visit_score"]}/100
الأولوية: {target["visit_priority"]}

هل يستحق تقديم يدوي؟
{manual_action}

ليش يستحق:
{chr(10).join("- " + item for item in target["why_visit"])}

مين تحاول توصل له:
{chr(10).join("- " + item for item in target["best_people"])}

وش تقول باختصار:
{target["what_to_say"]}

وش تبرز:
- {target["portfolio_angle"]}

رأيي:
- {target["visit_advice"]}
""".strip()
        )

    return "\n\n".join(lines)
